#!/usr/bin/env python3
"""Writes the connector logos both desktop apps show next to each app in Connect Apps (10.1).

The shapes come from Simple Icons (https://simpleicons.org, CC0-1.0). The logos themselves are trademarks of their owners and are used
only to say which service a connector talks to. Only data is read: the script parses the package's SVG and JSON files and never runs
code from it. To refresh:

    npm pack simple-icons@13.21.0 && mkdir si && tar xzf simple-icons-13.21.0.tgz -C si
    python3 scripts/build_connector_logos.py --package si/package [--outlook path/to/microsoftoutlook.svg]

Outputs desktop-windows/renderer/connector-logos.js and GrokBotMac/Composio/ConnectorLogos.swift.
"""
import argparse, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Connector slug -> Simple Icons slug
MAP = {
    'gmail': 'gmail', 'slack': 'slack', 'outlook': 'microsoftoutlook', 'discord': 'discord', 'zoom': 'zoom',
    'googlecalendar': 'googlecalendar', 'googledrive': 'googledrive', 'notion': 'notion', 'googledocs': 'googledocs',
    'googlesheets': 'googlesheets', 'asana': 'asana', 'trello': 'trello', 'todoist': 'todoist', 'clickup': 'clickup',
    'airtable': 'airtable', 'dropbox': 'dropbox', 'calendly': 'calendly', 'github': 'github', 'linear': 'linear',
    'gitlab': 'gitlab', 'bitbucket': 'bitbucket', 'jira': 'jira', 'sentry': 'sentry', 'vercel': 'vercel',
    'supabase': 'supabase', 'datadog': 'datadog', 'figma': 'figma', 'canva': 'canva', 'miro': 'miro',
    'hubspot': 'hubspot', 'salesforce': 'salesforce', 'stripe': 'stripe', 'shopify': 'shopify', 'zendesk': 'zendesk',
    'mailchimp': 'mailchimp', 'twitter': 'x', 'reddit': 'reddit', 'youtube': 'youtube', 'linkedin': 'linkedin',
}

def hex_of(package, name):
    for item in json.loads((package / '_data/simple-icons.json').read_text())['icons']:
        title = item['title']
        slug = item.get('slug') or re.sub(r'[^a-z0-9]', '', title.lower().replace('+', 'plus').replace('.', 'dot').replace('&', 'and'))
        if slug == name: return item['hex'].upper()
    raise SystemExit(f'No colour for {name}')

def path_of(svg_text):
    match = re.search(r'<path d="([^"]+)"', svg_text)
    if not match: raise SystemExit('No path in icon')
    return match.group(1)

def readable(hex_value):
    r, g, b = (int(hex_value[i:i + 2], 16) for i in (0, 2, 4))
    return '1F1F1F' if (0.299 * r + 0.587 * g + 0.114 * b) > 235 else hex_value

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--package', required=True, type=Path)
    parser.add_argument('--outlook', type=Path, help='microsoftoutlook.svg from an older Simple Icons release (newer ones dropped it)')
    arguments = parser.parse_args()
    logos = {}
    for slug, icon in MAP.items():
        file = arguments.package / 'icons' / f'{icon}.svg'
        if not file.exists() and slug == 'outlook' and arguments.outlook: file = arguments.outlook
        if not file.exists(): print(f'skipped {slug}: no {icon}.svg'); continue
        color = '0078D4' if slug == 'outlook' and file == arguments.outlook else hex_of(arguments.package, icon)
        logos[slug] = (readable(color), path_of(file.read_text()))
    notice = ('// Generated by scripts/build_connector_logos.py from Simple Icons (CC0-1.0). The logos are trademarks of their owners,\n'
              '// shown only to identify the service a connector talks to.\n')
    js = notice + 'export const logos = {\n' + ''.join(f'  {slug}: {{ hex: "{hexv}", path: "{path}" }},\n' for slug, (hexv, path) in logos.items()) + '};\n'
    (ROOT / 'desktop-windows/renderer/connector-logos.js').write_text(js)
    swift = notice + 'import Foundation\n\nenum ConnectorLogos {\n    struct Logo { let hex: String; let path: String }\n    static let all: [String: Logo] = [\n' \
        + ''.join(f'        "{slug}": Logo(hex: "{hexv}", path: "{path}"),\n' for slug, (hexv, path) in logos.items()) + '    ]\n}\n'
    (ROOT / 'GrokBotMac/Composio/ConnectorLogos.swift').write_text(swift)
    print(f'{len(logos)} logos written.')

main()
